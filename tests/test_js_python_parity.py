"""Cross-check: the browser and Python must agree on every shared derivation.

The personal oracle runs in JavaScript so a birth date never leaves the device, but
the tables it reads are generated by Python. If the two sides ever disagree about what
a birth date means, the site would quietly show a different fortune from the one the
tests here verify. So this drives the real personal.js through Node against vectors
produced by the Python implementation.

Skipped when Node is unavailable, since it is a convenience of the dev machine and CI
rather than a runtime dependency of the project.
"""

from __future__ import annotations

import json
import shutil
import subprocess
from datetime import date, timedelta
from pathlib import Path

import pytest

from tientrivutru import astrology, site

NODE = shutil.which("node")
PERSONAL_JS = Path(__file__).resolve().parents[1] / "site" / "personal.js"

pytestmark = pytest.mark.skipif(NODE is None, reason="node is not installed")

SAMPLE_BIRTHDAYS = [
    date(1930, 1, 29),   # the day before Tết 1930
    date(1930, 1, 30),   # Tết 1930 itself
    date(1968, 1, 29),   # the UTC+7 Tết Mậu Thân
    date(1984, 2, 2),
    date(1990, 1, 26),   # day before Tết 1990 - was broken by the floor bug
    date(1990, 1, 27),
    date(1995, 3, 12),
    date(1999, 12, 31),
    date(2000, 1, 1),
    date(2004, 2, 29),   # leap day
    date(2026, 2, 16),
    date(2026, 2, 17),
]
SAMPLE_NAMES = ["", "Nguyễn Quốc Đại", "Tran Thi Bich Ngoc", "Đỗ Đức Đông", "X Æ A-12"]


def _run_node(script: str) -> dict:
    result = subprocess.run(
        [NODE, "-e", script], capture_output=True, text=True, timeout=60, check=False
    )
    if result.returncode != 0:
        raise AssertionError(f"node failed:\n{result.stderr}")
    return json.loads(result.stdout)


def _harness(body: str) -> str:
    return f"""
    global.window = {{}};
    global.localStorage = {{ getItem: () => null, setItem: () => {{}}, removeItem: () => {{}} }};
    require({str(PERSONAL_JS)!r});
    const P = window.TienTriVuTruPersonal;
    {body}
    """


@pytest.fixture(scope="module")
def astro_payload() -> dict:
    return site._astrology_payload()


def test_western_sign_matches_python():
    days = [date(1996, 1, 1) + timedelta(days=n) for n in range(366)]
    bounds = json.dumps(
        [{"month": m, "day": d, "name": n} for m, d, n in astrology.ZODIAC_BOUNDS]
    )
    got = _run_node(
        _harness(
            f"const bounds = {bounds};"
            f"const days = {json.dumps([d.isoformat() for d in days])};"
            "const out = {};"
            "for (const d of days) out[d] = P.westernSign(d, bounds);"
            "console.log(JSON.stringify(out));"
        )
    )
    expected = {d.isoformat(): astrology.western_sign(d) for d in days}
    assert got == expected


