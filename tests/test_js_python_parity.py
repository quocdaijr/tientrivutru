def test_js_life_path_one_does_not_boost_every_number(astro_payload):
    """Same regression on the browser side: life path 1 must not select the whole pool."""
    got = _run_node(
        _harness(
            "const f = {lifePath:1, nameNumber:null, animal:'Ngọ', element:'Thủy',"
            " napAm:'Thiên Hà Thủy', westernSign:'Bảo Bình', guardianStar:null,"
            " tamHop:[], tuHanhXung:[]};"
            "const {reasons} = P.personalWeights(f, 45);"
            "const boosted = [...reasons.entries()]"
            "  .filter(([, why]) => why.some(w => w.includes('Số gốc')))"
            "  .map(([n]) => n);"
            "console.log(JSON.stringify({boosted}));"
        )
    )
    assert got["boosted"] == [1, 10, 19, 28, 37]
    assert len(got["boosted"]) < 45
