def test_out_of_range_birth_date_reports_clearly(astro_payload):
    """Regression: a January birth date before Tết falls into the PREVIOUS lunar year,
    so the table must cover a year earlier than the earliest supported birth year.
    Anything genuinely outside it must raise, not return null for the caller to trip on.
    """
    got = _run_node(
        _harness(
            f"const astro = {json.dumps(astro_payload)};"
            "const out = {};"
            "for (const b of ['1930-01-29', '1900-05-05', '2099-01-01']) {"
            "  try {"
            "    out[b] = P.readFortune({birthDate:b, name:'', gender:null}, astro,"
            "      '2026-08-19').canChi;"
            "  } catch (e) { out[b] = 'ERROR:' + e.constructor.name; }"
            "}"
            "console.log(JSON.stringify(out));"
        )
    )
    # 29 Jan 1930 precedes Tết (30 Jan), so it belongs to lunar 1929 - and must resolve.
    assert got["1930-01-29"] == astrology.can_chi_of_year(1929)
    assert got["1900-05-05"].startswith("ERROR:")
    assert got["2099-01-01"].startswith("ERROR:")


