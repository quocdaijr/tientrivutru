def test_lunar_year_lookup_matches_python(astro_payload):
    """The lookup-table shortcut must place every birth date in the same lunar year
    the full Python algorithm does."""
    days = [date(1930, 1, 1) + timedelta(days=n * 53) for n in range(660)]
    got = _run_node(
        _harness(
            f"const table = {json.dumps(astro_payload['lunar_years'])};"
            f"const days = {json.dumps([d.isoformat() for d in days])};"
            "const out = {};"
            "for (const d of days) out[d] = P.lunarYearOf(d, table);"
            "console.log(JSON.stringify(out));"
        )
    )
    for iso, js_year in got.items():
        day = date.fromisoformat(iso)
        if day.year > 2034:  # table ends before the algorithm does
            continue
        assert js_year == astrology.read_fortune(day).lunar_year, iso


def test_full_fortune_matches_python(astro_payload):
    """End to end: the fortune the browser shows must equal the Python one."""
    cases = [(d, "Nguyễn Quốc Đại", "nam") for d in SAMPLE_BIRTHDAYS]
    payload = [
        {"birthDate": d.isoformat(), "name": name, "gender": gender}
        for d, name, gender in cases
    ]
    got = _run_node(
        _harness(
            f"const astro = {json.dumps(astro_payload)};"
            f"const profiles = {json.dumps(payload)};"
            "const out = profiles.map(p => P.readFortune(p, astro, '2026-08-19'));"
            "console.log(JSON.stringify(out));"
        )
    )
    for (day, name, gender), js in zip(cases, got, strict=True):
        py = astrology.read_fortune(day, name=name, gender=gender, today=date(2026, 8, 19))
        assert js["lunarYear"] == py.lunar_year, day
        assert js["canChi"] == py.can_chi, day
        assert js["animal"] == py.zodiac_animal, day
        assert js["napAm"] == py.nap_am, day
        assert js["element"] == py.element, day
        assert js["westernSign"] == py.western_sign, day
        assert js["lifePath"] == py.life_path, day
        assert js["nameNumber"] == py.name_number, day
        assert js["guardianStar"] == py.guardian_star, day
        assert js["tamHop"] == list(py.tam_hop), day
        assert js["tuHanhXung"] == list(py.tu_hanh_xung), day


def test_personal_prophecy_is_deterministic(astro_payload):
    """Same person, same draw -> same twelve numbers, exactly like the house oracle."""
    got = _run_node(
        _harness(
            f"const astro = {json.dumps(astro_payload)};"
            "const profile = {birthDate:'1995-03-12', name:'Nguyễn Quốc Đại', gender:'nam'};"
            "const game = {key:'mega645', pool:45, pick:6};"
            "const f = P.readFortune(profile, astro, '2026-08-19');"
            "const a = P.personalProphecy(profile, f, game, '01551', '2026-08-19');"
            "const b = P.personalProphecy(profile, f, game, '01551', '2026-08-19');"
            "const c = P.personalProphecy(profile, f, game, '01552', '2026-08-21');"
            "console.log(JSON.stringify({a:a.numbers, b:b.numbers, c:c.numbers,"
            " sermonA:a.sermon, sermonB:b.sermon}));"
        )
    )
    assert got["a"] == got["b"], "same inputs must produce the same numbers"
    assert got["sermonA"] == got["sermonB"]
    assert got["a"] != got["c"], "a different draw must produce different numbers"


def test_personal_prophecy_shape(astro_payload):
    got = _run_node(
        _harness(
            f"const astro = {json.dumps(astro_payload)};"
            "const out = [];"
            "for (const g of [{key:'mega645',pool:45,pick:6},{key:'power655',pool:55,pick:6}]) {"
            "  for (const b of ['1930-01-30','1990-01-27','2004-02-29','2026-02-17']) {"
            "    const profile = {birthDate:b, name:'', gender:null};"
            "    const f = P.readFortune(profile, astro, '2026-08-19');"
            "    out.push({game:g.key, pool:g.pool,"
            "      numbers:P.personalProphecy(profile, f, g, '00001', '2026-08-19').numbers});"
            "  }"
            "}"
            "console.log(JSON.stringify(out));"
        )
    )
    for entry in got:
        numbers = entry["numbers"]
        assert len(numbers) == 12, entry
        assert len(set(numbers)) == 12, entry
        assert numbers == sorted(numbers), entry
        assert all(1 <= n <= entry["pool"] for n in numbers), entry


